#[test]
fn hpb9_process_site_equals_direct_publication() {
    let p = project("Site project", "SITECANARY", [9, 99, 199]);
    for selector in [p.id("$orgp"), IMPLICIT_ORG.to_string()] {
        let direct = p.direct(&selector);
        let (summary, out, a) = process(&p.request(&selector, RenderFormat::Site));
        same(&a, &direct, &selector);
        assert!(a.files.values().any(|f| *f == p.figure), "{selector}");
        assert_eq!(summary.manifest_hash, direct.manifest_hash);
        assert_eq!(summary.files as usize, direct.files.len());
        let bytes: u64 = direct.manifest.files.iter().map(|e| e.size).sum();
        assert_eq!(summary.bytes, bytes);
        // the framing: metadata, then each file's raw bytes in manifest path order
        let (meta, files) = split(&out);
        assert_eq!(meta["manifest_recipe"], json!(1));
        assert_eq!(
            meta["manifest_hash"],
            json!(direct.manifest_hash.to_string())
        );
        assert_eq!(
            meta.as_object().unwrap().keys().collect::<Vec<_>>(),
            ["manifest", "manifest_hash", "manifest_recipe", "warnings"]
        );
        let paths: Vec<&String> = direct.files.keys().collect();
        for (i, path) in paths.iter().enumerate() {
            assert_eq!(meta["manifest"]["files"][i]["path"], json!(path));
            assert!(files[i] == direct.files[*path], "{path}");
        }
        // an explicit profile shows its own title, the implicit one the captured source title
        let index = String::from_utf8(a.files["index.html"].clone()).unwrap();
        let title = if selector == IMPLICIT_ORG {
            "Site project"
        } else {
            "Site project org site"
        };
        assert!(index.contains(title), "{selector}");
    }
    // the org profile's reference warning comes first, as the direct build gives it
    let (_, _, a) = process(&p.request(&p.id("$orgp"), RenderFormat::Site));
    assert!(
        a.warnings.first().is_some_and(|w| w.contains("outside")),
        "{:?}",
        a.warnings
    );
}

#[test]
fn hpb9_process_markdown_uses_the_print_sink() {
    let p = project("Print project", "PRINTCANARY", [1, 2, 3]);
    for selector in [p.id("$orgp"), IMPLICIT_ORG.to_string()] {
        let print = print::build_profile(&p.r.read(), &format!("tag:{TAG}"), &selector).unwrap();
        for (format, layout) in [
            (RenderFormat::Markdown, Layout::Plain),
            (RenderFormat::Techdocs, Layout::Techdocs),
        ] {
            let what = format!("{selector} {}", layout.name());
            let mut want: BTreeMap<String, Vec<u8>> = BTreeMap::new();
            emit_files(&print, layout, true, |path, data| {
                assert!(want.insert(path.to_string(), data.to_vec()).is_none());
                Ok(())
            })
            .unwrap();
            let (summary, _, a) = process(&p.request(&selector, format));
            assert_eq!(a.files, want, "{what}");
            assert_eq!(a.warnings, print.warnings, "{what}");
            assert_eq!(summary.files as usize, want.len(), "{what}");
            assert_eq!(
                a.manifest_hash,
                manifest_hash(&a.manifest, MANIFEST_RECIPE).unwrap()
            );
            assert_eq!(summary.manifest_hash, a.manifest_hash);
            for e in &a.manifest.files {
                assert_eq!(e.notice_offset, None, "{what}: {}", e.path);
                assert_eq!(e.hash, Hash::of(&a.files[&e.path]), "{what}: {}", e.path);
                assert_eq!(e.size, a.files[&e.path].len() as u64, "{what}: {}", e.path);
                let text = String::from_utf8_lossy(&a.files[&e.path]).into_owned();
                if e.path.ends_with(".md") {
                    assert_eq!(e.media_type, "text/markdown", "{what}");
                    // the front matter first, then the generated header
                    assert!(text.starts_with("---\n"), "{what}: {}", e.path);
                    assert!(text.contains(&format!("---\n\n{MD_MARK}\n\n")), "{what}");
                } else if e.path == "mkdocs.yml" {
                    assert_eq!(e.media_type, "application/yaml", "{what}");
                    assert!(text.starts_with(YAML_MARK), "{what}");
                    assert!(text.contains("docs_dir: docs\n"), "{what}");
                    assert!(text.contains("  - techdocs-core\n"), "{what}");
                } else {
                    // a copied asset keeps every byte
                    assert_eq!(e.media_type, "image/png", "{what}");
                    assert!(a.files[&e.path] == p.figure, "{what}");
                }
            }
            let has_yaml = a.files.contains_key("mkdocs.yml");
            match layout {
                Layout::Plain => {
                    assert!(!has_yaml, "{what}");
                    assert!(a.files.contains_key("index.md"), "{what}");
                    assert!(!a.files.keys().any(|k| k.starts_with("docs/")), "{what}");
                }
                _ => {
                    assert!(has_yaml, "{what}");
                    assert!(
                        a.files
                            .keys()
                            .all(|k| k == "mkdocs.yml" || k.starts_with("docs/")),
                        "{what}"
                    );
                }
            }
            assert!(
                a.files
                    .values()
                    .any(|f| String::from_utf8_lossy(f).contains("PRINTCANARY")),
                "{what}"
            );
            // no HTML page and no notice slot in a Markdown artifact
            assert!(!a.files.keys().any(|k| k.ends_with(".html")), "{what}");
        }
    }
}

