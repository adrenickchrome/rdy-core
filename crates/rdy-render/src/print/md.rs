//! The print as a tree of Markdown files (D-K7ZFK, O28, O29).
//!
//! One file per page of the print, at the page's site path with `.md` for `.html`; each folder is
//! its folder's `index.md`; the glossary is `glossary.md`; each figure is a file under `assets/`
//! with the site's name for it. The title part is `index.md` at the root. Every file starts with
//! front matter, then a `# <title>` line. A reference is a relative link to a file and an anchor;
//! a block's id appears in no file but in the front matter of its folder or doc (O4). With
//! [`Layout::Mkdocs`] the tree sits under `docs/` and `mkdocs.yml` names the tree as `nav`.
//! [`Layout::Techdocs`] is that tree for Backstage TechDocs: `mkdocs.yml` also names `docs_dir`
//! and the `techdocs-core` plugin (D-5X0ZK), and every generated Markdown and YAML file says that
//! rdy generated it (D-6A37C). Copied assets keep every byte.
//!
//! The tree is written to a staging directory beside `out` and renamed into place, so `out` holds
//! the whole tree or nothing. The module makes portable `std::fs` calls only (D-1RXEA).
//!
//! The same block writer gives Copy its Markdown ([`copy_parts`], D-BRF4P, D-E8P8J): a fragment
//! of a site page, with no front matter and no anchor line, whose links lead to the site's pages.
use super::{Href, PBlock, PageKind, Print, PrintDoc, PrintSummary, Run};
use crate::llms::md_escape as llms_escape;
use rdy_engine::{E_BAD_INPUT, E_IO, RdyError};
use rdy_model::Hash;
use std::collections::BTreeMap;
use std::io::Write;
use std::path::Path;

/// How the tree is laid out.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Layout {
    /// The files of the print, directly under `out`.
    Plain,
    /// The files under `<out>/docs/`, and `<out>/mkdocs.yml` with the tree as `nav`.
    Mkdocs,
    /// The `Mkdocs` tree for Backstage TechDocs: `mkdocs.yml` names `docs_dir: docs` and the
    /// `techdocs-core` plugin, and each generated Markdown and YAML file starts with a header
    /// that says rdy generated it.
    Techdocs,
}

impl Layout {
    /// The layout as the CLI and the tools name it.
    pub fn name(self) -> &'static str {
        match self {
            Layout::Plain => "plain",
            Layout::Mkdocs => "mkdocs",
            Layout::Techdocs => "techdocs",
        }
    }
}

/// The line that follows the front matter of a generated Markdown file, after one blank line and
/// before another.
const MD_MARK: &str = "<!-- generated by rdy, edit in rdy -->";

/// The first line of a generated YAML file.
const YAML_MARK: &str = "# generated by rdy, edit in rdy\n";

/// A list item's content starts in this column or later, so a block inside it keeps its
/// indentation in every reader (CommonMark needs the content's column, Python-Markdown four
/// spaces).
const ITEM_COLUMN: usize = 4;

/// The `.md` path of a site page.
fn md_path(page: &str) -> String {
    format!("{}.md", page.strip_suffix(".html").unwrap_or(page))
}

/// The path to `to` (a path in the tree) from the file `from` (a path in the tree).
fn relative(from: &str, to: &str) -> String {
    let mut dir: Vec<&str> = from.split('/').collect();
    dir.pop();
    let target: Vec<&str> = to.split('/').collect();
    let common = dir
        .iter()
        .zip(&target[..target.len() - 1])
        .take_while(|(a, b)| a == b)
        .count();
    let ups = "../".repeat(dir.len() - common);
    format!("{ups}{}", target[common..].join("/"))
}

/// What a page needs to write its blocks.
struct Cx<'a> {
    /// The path the links are written from: the `.md` path of the file being written, or the
    /// site page a fragment is copied from.
    from: &'a str,
    /// The figures of the print.
    blobs: &'a BTreeMap<Hash, super::Blob>,
    /// A fragment ([`copy_parts`]): a link leads to the site page (`.html`), and no block writes
    /// its anchor line.
    fragment: bool,
}

/// One part of a Copy fragment ([`copy_parts`]): literal Markdown, or a link target.
#[derive(Clone, Debug, PartialEq, Eq, serde::Serialize)]
#[serde(tag = "kind", content = "value", rename_all = "snake_case")]
pub enum CopyPart {
    /// Markdown, written as the export writes it.
    Text(String),
    /// A link target as the page names it: a path relative to the page the fragment is copied
    /// from, with its anchor, or an authored external URL. The reader of the fragment resolves
    /// it and writes it in Markdown's link-target escape.
    Url(String),
}

/// A piece of Markdown as the block writer builds it.
#[derive(Clone, Debug)]
enum Seg {
    Text(String),
    /// A link target before its escape. `cell` says it sits in a table cell, where a `|` would
    /// end the cell.
    Url {
        raw: String,
        cell: bool,
    },
}

/// Markdown with its link targets kept apart: the export writes each target escaped in place
/// ([`Md::export`]), and a fragment hands it over as a [`CopyPart::Url`] ([`Md::into_parts`]).
/// It never holds an empty text piece or two text pieces side by side.
#[derive(Clone, Debug, Default)]
struct Md(Vec<Seg>);

impl Md {
    fn text(s: &str) -> Md {
        let mut md = Md::default();
        md.push_str(s);
        md
    }

    fn is_empty(&self) -> bool {
        self.0.is_empty()
    }

    /// `self` shows nothing: no link target, and text of white space only.
    fn is_blank(&self) -> bool {
        self.0
            .iter()
            .all(|seg| matches!(seg, Seg::Text(t) if t.trim().is_empty()))
    }

    fn push_str(&mut self, s: &str) {
        if s.is_empty() {
            return;
        }
        match self.0.last_mut() {
            Some(Seg::Text(t)) => t.push_str(s),
            _ => self.0.push(Seg::Text(s.to_string())),
        }
    }

    fn push_url(&mut self, raw: String) {
        self.0.push(Seg::Url { raw, cell: false });
    }

    fn append(&mut self, other: Md) {
        for seg in other.0 {
            match seg {
                Seg::Text(t) => self.push_str(&t),
                url => self.0.push(url),
            }
        }
    }

    /// `prefix`, then `self`.
    fn prefixed(self, prefix: &str) -> Md {
        let mut md = Md::text(prefix);
        md.append(self);
        md
    }

    /// The lines of `self`: a link target never holds a line break.
    fn lines(self) -> Vec<Md> {
        let mut out = vec![Md::default()];
        for seg in self.0 {
            match seg {
                Seg::Text(t) => {
                    for (i, line) in t.split('\n').enumerate() {
                        if i > 0 {
                            out.push(Md::default());
                        }
                        out.last_mut().expect("a line").push_str(line);
                    }
                }
                url => out.last_mut().expect("a line").0.push(url),
            }
        }
        out
    }

    /// `self` as a table cell: a `|` is `\|` in its text, and its link targets keep one too.
    fn cell(self) -> Md {
        Md(self
            .0
            .into_iter()
            .map(|seg| match seg {
                Seg::Text(t) => Seg::Text(t.replace('|', "\\|")),
                Seg::Url { raw, .. } => Seg::Url { raw, cell: true },
            })
            .collect())
    }

    /// `f` applied to the text that starts `self`; a line starts with text, as a link starts
    /// with `[`.
    fn map_first(mut self, f: impl FnOnce(&str) -> String) -> Md {
        if let Some(Seg::Text(t)) = self.0.first_mut() {
            *t = f(t);
            if t.is_empty() {
                self.0.remove(0);
            }
        }
        self
    }

    /// `f` applied to the text that ends `self`; a line ends with text, as a link ends with `)`.
    fn map_last(mut self, f: impl FnOnce(&str) -> String) -> Md {
        if let Some(Seg::Text(t)) = self.0.last_mut() {
            *t = f(t);
            if t.is_empty() {
                self.0.pop();
            }
        }
        self
    }

    /// The export's Markdown: each link target escaped in place.
    fn export(&self) -> String {
        let mut out = String::new();
        for seg in &self.0 {
            match seg {
                Seg::Text(t) => out.push_str(t),
                Seg::Url { raw, cell: false } => out.push_str(&url(raw)),
                Seg::Url { raw, cell: true } => out.push_str(&url(raw).replace('|', "\\|")),
            }
        }
        out
    }

    /// Hands `self` to a fragment's parts. A target in a table cell writes its `|` as `%7C`,
    /// which leads to the same place and leaves the cell whole.
    fn into_parts(self, out: &mut Vec<CopyPart>) {
        for seg in self.0 {
            match seg {
                Seg::Text(t) => push_text(out, &t),
                Seg::Url { raw, cell } => out.push(CopyPart::Url(if cell {
                    raw.replace('|', "%7C")
                } else {
                    raw
                })),
            }
        }
    }
}

/// `s` at the end of `out`, in the text part that ends it when there is one.
fn push_text(out: &mut Vec<CopyPart>, s: &str) {
    if s.is_empty() {
        return;
    }
    match out.last_mut() {
        Some(CopyPart::Text(t)) => t.push_str(s),
        _ => out.push(CopyPart::Text(s.to_string())),
    }
}

/// `s` with each `&` that opens something a reader takes for a character reference written as
/// `&amp;`, which every reader shows as `&`: the text `&copy;` stays `&copy;` and never becomes
/// `©`.
fn entities(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(i) = rest.find('&') {
        out.push_str(&rest[..i]);
        let tail = &rest[i + 1..];
        let name = tail.strip_prefix('#').unwrap_or(tail);
        let len = name.bytes().take_while(u8::is_ascii_alphanumeric).count();
        out.push_str(if len > 0 && name[len..].starts_with(';') {
            "&amp;"
        } else {
            "&"
        });
        rest = tail;
    }
    out.push_str(rest);
    out
}

/// The exporter's text escape: the llms escape (the characters that start markup), and the
/// character references that it leaves alone.
fn md_escape(s: &str, line_start: bool) -> String {
    entities(&llms_escape(s, line_start))
}

/// One line of a paragraph (or of text like it) that no reader takes for the underline of the
/// line before it (`===`) or for a tilde fence (`~~~`): its first such character is the
/// reference `&#61;` or `&#126;`, which every reader shows as the character.
fn guard_line(line: &str) -> String {
    let text = line.trim_start();
    let lead = &line[..line.len() - text.len()];
    let rest = &text[text.chars().next().map_or(0, char::len_utf8)..];
    if !text.is_empty() && text.trim_end().bytes().all(|b| b == b'=') {
        format!("{lead}&#61;{rest}")
    } else if text.starts_with("~~~") {
        format!("{lead}&#126;{rest}")
    } else {
        line.to_string()
    }
}

/// The lines of `text` (already escaped), each guarded by [`guard_line`]. A line's guard reads
/// the text that starts it: a line with a link is never all `=`.
fn guarded_lines(text: Md) -> Vec<Md> {
    text.lines()
        .into_iter()
        .map(|l| l.map_first(guard_line))
        .collect()
}

/// An ATX heading line. `text` is escaped; a `#` that ends it is text, not a closing sequence.
fn heading(level: usize, text: &str) -> String {
    heading_md(level, Md::text(text)).export()
}

/// [`heading`] of Markdown that may hold links.
fn heading_md(level: usize, text: Md) -> Md {
    let text = text.map_last(|t| match t.strip_suffix('#') {
        Some(rest) => format!("{rest}\\#"),
        None => t.to_string(),
    });
    let mut line = Md::text(&"#".repeat(level.clamp(1, 6)));
    line.push_str(" ");
    line.append(text);
    line.map_last(|t| t.trim_end().to_string())
}

/// A link target as Markdown reads it inside `(…)`.
fn url(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    for c in raw.chars() {
        match c {
            ' ' => out.push_str("%20"),
            '(' => out.push_str("%28"),
            ')' => out.push_str("%29"),
            '<' => out.push_str("%3C"),
            '>' => out.push_str("%3E"),
            '\n' | '\r' | '\t' => {}
            c => out.push(c),
        }
    }
    entities(&out)
}

/// A piece of code as an inline code span: its delimiter is longer than any backtick run inside.
fn code_span(s: &str) -> String {
    let delim = "`".repeat(longest_backticks(s) + 1);
    if s.starts_with('`') || s.ends_with('`') {
        format!("{delim} {s} {delim}")
    } else {
        format!("{delim}{s}{delim}")
    }
}

fn longest_backticks(s: &str) -> usize {
    let (mut best, mut run) = (0, 0);
    for c in s.chars() {
        run = if c == '`' { run + 1 } else { 0 };
        best = best.max(run);
    }
    best
}

impl Cx<'_> {
    /// Where a link leads, before its escape: the export's `.md` file, or a fragment's site page.
    fn target(&self, href: &Href) -> String {
        match href {
            Href::External(u) => u.clone(),
            Href::Page { page, anchor } => {
                let mut t = if self.fragment {
                    relative(self.from, page)
                } else {
                    relative(self.from, &md_path(page))
                };
                if let Some(a) = anchor {
                    t.push('#');
                    t.push_str(a);
                }
                t
            }
        }
    }

    /// The words of one run's piece of a line, in the run's look.
    fn piece(&self, run: &Run, piece: &str, line_start: bool) -> Md {
        let core = piece.trim();
        if core.is_empty() {
            return Md::text(piece);
        }
        let lead = &piece[..piece.len() - piece.trim_start().len()];
        let trail = &piece[piece.trim_end().len()..];
        let plain = !(run.code || run.bold || run.italic || run.link.is_some());
        let mut out = if run.code {
            code_span(core)
        } else {
            md_escape(core, line_start && plain)
        };
        out = match (run.bold, run.italic) {
            (true, true) => format!("***{out}***"),
            (true, false) => format!("**{out}**"),
            (false, true) => format!("*{out}*"),
            (false, false) => out,
        };
        let mut md = Md::text(lead);
        match &run.link {
            Some(href) => {
                md.push_str(&format!("[{out}]("));
                md.push_url(self.target(href));
                md.push_str(")");
            }
            None => md.push_str(&out),
        }
        md.push_str(trail);
        md
    }

    /// Runs as one piece of Markdown text; a line break in a run is `br`.
    fn inline(&self, runs: &[Run], br: &str, line_start: bool) -> Md {
        let mut out = Md::default();
        let mut start = line_start;
        for run in runs {
            for (i, piece) in run.text.split('\n').enumerate() {
                if i > 0 {
                    out.push_str(br);
                    start = br.contains('\n');
                }
                if piece.is_empty() {
                    continue;
                }
                out.append(self.piece(run, piece, start));
                start = false;
            }
        }
        out
    }

    /// The lines of `b`, or `None` when it writes nothing: no line, or in a fragment no line that
    /// shows anything (an empty paragraph), so it adds no blank line around it. The export keeps
    /// such a block's lines.
    fn written(&self, b: &PBlock) -> Option<Vec<Md>> {
        let lines = self.block(b);
        let shows = if self.fragment {
            lines.iter().any(|l| !l.is_blank())
        } else {
            !lines.is_empty()
        };
        shows.then_some(lines)
    }

    /// The lines of `blocks`, one blank line between blocks.
    fn blocks(&self, blocks: &[PBlock]) -> Vec<Md> {
        let mut out: Vec<Md> = vec![];
        for b in blocks {
            let Some(lines) = self.written(b) else {
                continue;
            };
            if !out.is_empty() {
                out.push(Md::default());
            }
            out.extend(lines);
        }
        out
    }

    fn block(&self, b: &PBlock) -> Vec<Md> {
        match b {
            PBlock::Heading {
                level,
                anchor,
                runs,
            } => {
                let text = self.inline(runs, " ", false);
                self.anchored(anchor, true, vec![heading_md(usize::from(*level), text)])
            }
            PBlock::Para { anchor, runs } => {
                let text = self.inline(runs, "\\\n", true);
                self.anchored(anchor, true, guarded_lines(text))
            }
            PBlock::List {
                ordered,
                start,
                items,
            } => self.list(*ordered, *start, items),
            PBlock::Table { anchor, head, rows } => {
                self.anchored(anchor, false, self.table(head, rows))
            }
            PBlock::Code { anchor, lang, text } => {
                let fence = "`".repeat((longest_backticks(text) + 1).max(3));
                let info = lang
                    .as_deref()
                    .filter(|l| !l.chars().any(|c| c.is_whitespace() || c == '`'))
                    .unwrap_or("");
                let mut lines = vec![Md::text(&format!("{fence}{info}"))];
                if !text.is_empty() {
                    lines.extend(text.split('\n').map(Md::text));
                }
                lines.push(Md::text(&fence));
                self.anchored(anchor, false, lines)
            }
            PBlock::Figure {
                anchor,
                blob,
                alt,
                caption,
            } => {
                let mut lines = vec![];
                let file = blob.and_then(|h| self.blobs.get(&h)).map(|b| &b.file);
                let alt_text = alt.split_whitespace().collect::<Vec<_>>().join(" ");
                if let Some(file) = file {
                    let mut image = Md::text(&format!("![{}](", md_escape(&alt_text, false)));
                    image.push_url(relative(self.from, file));
                    image.push_str(")");
                    lines.push(image);
                }
                let caption = self.inline(caption, "\\\n", true);
                if file.is_none() && caption.is_empty() && !alt_text.is_empty() {
                    lines.push(Md::text(&guard_line(&md_escape(&alt_text, true))));
                }
                if !caption.is_empty() {
                    if !lines.is_empty() {
                        lines.push(Md::default());
                    }
                    lines.extend(guarded_lines(caption));
                }
                self.anchored(anchor, false, lines)
            }
            PBlock::Callout {
                anchor,
                label,
                blocks,
            } => {
                let mut lines = vec![];
                let label = label.split_whitespace().collect::<Vec<_>>().join(" ");
                let inner = self.blocks(blocks);
                if !label.is_empty() {
                    lines.push(Md::text(&format!("> **{}**", md_escape(&label, false))));
                    if !inner.is_empty() {
                        lines.push(Md::text(">"));
                    }
                }
                lines.extend(inner.into_iter().map(|l| {
                    if l.is_empty() {
                        Md::text(">")
                    } else {
                        l.prefixed("> ")
                    }
                }));
                self.anchored(anchor, false, lines)
            }
        }
    }

    fn list(&self, ordered: bool, start: u32, items: &[Vec<PBlock>]) -> Vec<Md> {
        let mut out = vec![];
        for (i, item) in items.iter().enumerate() {
            let mark = if ordered {
                format!("{}.", u64::from(start) + i as u64)
            } else {
                "-".to_string()
            };
            let width = (mark.len() + 1).max(ITEM_COLUMN);
            let marker = format!("{mark:<width$}");
            let mut lines = self.blocks(item).into_iter();
            match lines.next() {
                Some(first) => out.push(first.prefixed(&marker)),
                None => out.push(Md::text(&mark)),
            }
            let pad = " ".repeat(width);
            out.extend(lines.map(|l| if l.is_empty() { l } else { l.prefixed(&pad) }));
        }
        out
    }

    /// A pipe table: a cell writes `|` as `\|` and joins its lines with one space (O28 (e)).
    fn table(&self, head: &[Vec<Run>], rows: &[Vec<Vec<Run>>]) -> Vec<Md> {
        let cols = rows
            .iter()
            .map(Vec::len)
            .chain([head.len()])
            .max()
            .unwrap_or(0);
        if cols == 0 {
            return vec![];
        }
        let row = |cells: &[Vec<Run>]| {
            let mut texts: Vec<Md> = cells
                .iter()
                .map(|c| self.inline(c, " ", false).cell())
                .collect();
            texts.resize(cols, Md::default());
            let mut line = Md::text("| ");
            for (i, cell) in texts.into_iter().enumerate() {
                if i > 0 {
                    line.push_str(" | ");
                }
                line.append(cell);
            }
            line.push_str(" |");
            line
        };
        let mut lines = vec![row(head), Md::text(&format!("|{}", " --- |".repeat(cols)))];
        lines.extend(rows.iter().map(|r| row(r)));
        lines
    }

    /// `lines` after the line that names their anchor. A heading and a paragraph follow it
    /// directly; any other block follows a blank line, so a reader that needs the blank line
    /// finds it. A fragment writes no anchor line (D-E8P8J).
    fn anchored(&self, anchor: &Option<String>, adjacent: bool, lines: Vec<Md>) -> Vec<Md> {
        let Some(a) = anchor.as_ref().filter(|_| !self.fragment) else {
            return lines;
        };
        let mut out = vec![Md::text(&format!(
            "<a id=\"{}\"></a>",
            a.replace('"', "&quot;")
        ))];
        if !lines.is_empty() && !adjacent {
            out.push(Md::default());
        }
        out.extend(lines);
        out
    }
}

/// Copy's Markdown of `blocks` on the site page `page` (D-BRF4P, D-E8P8J): the blocks as the
/// export writes them, one blank line between blocks and one line feed at the end, with no front
/// matter and no anchor line. A link leads to the site page (`.html`) and the anchor the print
/// gives it; each target is a [`CopyPart::Url`] relative to `page`, so the reader resolves it
/// against the page it shows. A diagram is its source, fenced in its language; a removed block is
/// its notice. No two text parts are side by side, and an empty range has no part. Each block is
/// written into the result once, as it is read: the page's own bounds hold, and nothing else
/// caps the result.
pub fn copy_parts(
    blocks: &[PBlock],
    page: &str,
    blobs: &BTreeMap<Hash, super::Blob>,
) -> Result<Vec<CopyPart>, RdyError> {
    let cx = Cx {
        from: page,
        blobs,
        fragment: true,
    };
    let mut out = vec![];
    for b in blocks {
        let Some(lines) = cx.written(b) else {
            continue;
        };
        if !out.is_empty() {
            push_text(&mut out, "\n\n");
        }
        for (i, line) in lines.into_iter().enumerate() {
            if i > 0 {
                push_text(&mut out, "\n");
            }
            line.into_parts(&mut out);
        }
    }
    if !out.is_empty() {
        push_text(&mut out, "\n");
    }
    Ok(out)
}

/// A string as YAML reads it: a JSON string (O28 (c)).
fn json(s: &str) -> String {
    serde_json::to_string(s).expect("a string is JSON")
}

/// One line of text with the Markdown it would otherwise open escaped.
fn text_line(s: &str, line_start: bool) -> String {
    md_escape(
        &s.split_whitespace().collect::<Vec<_>>().join(" "),
        line_start,
    )
}

/// The header of a generated file: after the front matter and its blank line, the mark and one
/// more blank line.
fn push_mark(out: &mut String, generated: bool) {
    if generated {
        out.push_str(MD_MARK);
        out.push_str("\n\n");
    }
}

/// The file of a folder, doc or the glossary.
fn page_file(p: &Print, d: &PrintDoc, generated: bool) -> String {
    let mut out = String::from("---\n");
    out.push_str(&format!("title: {}\n", json(&d.title)));
    if d.kind != PageKind::Glossary {
        out.push_str(&format!("rdy_id: {}\n", d.id));
    }
    out.push_str("---\n\n");
    push_mark(&mut out, generated);
    out.push_str(&format!("{}\n", heading(1, &text_line(&d.title, false))));
    let file = md_path(&d.page);
    let cx = Cx {
        from: &file,
        blobs: &p.blobs,
        fragment: false,
    };
    let lines = cx.blocks(&d.blocks);
    if !lines.is_empty() {
        out.push('\n');
        for (i, line) in lines.iter().enumerate() {
            if i > 0 {
                out.push('\n');
            }
            out.push_str(&line.export());
        }
        out.push('\n');
    }
    out
}

/// The title part (O2, O28 (a)).
fn title_file(p: &Print, generated: bool) -> String {
    let mut out = format!("---\ntitle: {}\n---\n\n", json(&p.title));
    push_mark(&mut out, generated);
    out.push_str(&format!("{}\n", heading(1, &text_line(&p.title, false))));
    if let Some(d) = p
        .description
        .as_deref()
        .map(str::trim)
        .filter(|d| !d.is_empty())
    {
        let paras: Vec<String> = d
            .split("\n\n")
            .map(|para| {
                para.lines()
                    .map(|l| guard_line(&md_escape(l.trim(), true)))
                    .collect::<Vec<_>>()
                    .join("\n")
            })
            .collect();
        out.push('\n');
        out.push_str(&paras.join("\n\n"));
        out.push('\n');
    }
    // an empty label or scope (a named profile's, RULING F3) leaves no line and no blank line;
    // an affected chosen tag's label keeps its redacted marker
    for (name, value, suffix) in [
        ("Version", &p.label, p.redacted_suffix()),
        ("Scope", &p.scope, ""),
    ] {
        if !value.is_empty() {
            out.push_str(&format!("\n{name}: {}{suffix}\n", text_line(value, false)));
        }
    }
    out
}

/// `mkdocs.yml`: the site's name, then the tree as `nav` (O28 (d)). A generated file starts with
/// its mark; the TechDocs layout names `docs_dir` and the plugin between the two.
fn mkdocs_yml(p: &Print, layout: Layout, generated: bool) -> String {
    let mut out = String::new();
    if generated {
        out.push_str(YAML_MARK);
    }
    out.push_str(&format!("site_name: {}\n", json(&p.title)));
    if layout == Layout::Techdocs {
        out.push_str("docs_dir: docs\nplugins:\n  - techdocs-core\n");
    }
    out.push_str("nav:\n");
    out.push_str(&format!("  - {}: index.md\n", json(&p.title)));
    for d in &p.docs {
        let pad = " ".repeat(2 + 4 * d.depth);
        let (title, path) = (json(&d.title), md_path(&d.page));
        match d.kind {
            PageKind::Folder => {
                let inner = " ".repeat(2 + 4 * (d.depth + 1));
                out.push_str(&format!("{pad}- {title}:\n{inner}- {title}: {path}\n"));
            }
            PageKind::Doc => out.push_str(&format!("{pad}- {title}: {path}\n")),
            PageKind::Glossary => out.push_str("  - Glossary: glossary.md\n"),
        }
    }
    out
}

fn io(path: &Path, e: std::io::Error) -> RdyError {
    RdyError::new(
        E_IO,
        format!("{}: {e}", path.display()),
        "check the output directory",
    )
}

/// Writes one file, durably.
fn put(path: &Path, bytes: &[u8]) -> Result<(), RdyError> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| io(dir, e))?;
    }
    let mut file = std::fs::File::options()
        .write(true)
        .create_new(true)
        .open(path)
        .map_err(|e| io(path, e))?;
    file.write_all(bytes).map_err(|e| io(path, e))?;
    file.sync_all().map_err(|e| io(path, e))
}

/// The refusals of O29 (`super::check_out`) and the Markdown export's own. `Ok(true)` when
/// `out` is an empty directory, which the rename replaces.
fn check_out(p: &Print, out: &Path) -> Result<bool, RdyError> {
    super::check_out(&p.rdy_dir, out)?;
    match std::fs::symlink_metadata(out) {
        Ok(md) if md.is_dir() => {
            if std::fs::read_dir(out)
                .map_err(|e| io(out, e))?
                .next()
                .is_some()
            {
                return Err(RdyError::new(
                    E_BAD_INPUT,
                    format!("{} is not empty", out.display()),
                    "choose an empty directory (or one that does not exist yet) so no stale files mix into the export",
                ));
            }
            Ok(true)
        }
        Ok(_) => Err(RdyError::new(
            E_BAD_INPUT,
            format!(
                "{} is a file: a Markdown export writes a directory",
                out.display()
            ),
            "pass a directory path such as ./docs-md",
        )),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(false),
        Err(e) => Err(io(out, e)),
    }
}

/// Writes `p` as a Markdown tree at `out`: a directory that does not exist or is empty. The
/// same print gives the same bytes (O15).
pub fn write_markdown(p: &Print, out: &Path, layout: Layout) -> Result<PrintSummary, RdyError> {
    let replaces_empty = check_out(p, out)?;
    let (parent, name) = super::parent_and_name(out)?;
    // everything is written to a staging directory beside `out` and renamed into place at the
    // end: a failure leaves nothing behind. The directory is ours only if `create_dir` made it:
    // a path that is already there is somebody's (a file of the user's, or the staging of an
    // export that runs now), so it is refused and never touched
    let staging = parent.join(format!(".{}.rdy-export-partial", name.to_string_lossy()));
    match std::fs::create_dir(&staging) {
        Ok(()) => {}
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {
            return Err(RdyError::new(
                E_BAD_INPUT,
                format!(
                    "{} already exists: a Markdown export may be running, or an earlier one stopped",
                    staging.display()
                ),
                "if no export is running, remove it and export again",
            ));
        }
        Err(e) => return Err(io(&staging, e)),
    }
    let bytes = match write_tree(p, &staging, layout) {
        Ok(bytes) => bytes,
        Err(e) => {
            let _ = std::fs::remove_dir_all(&staging);
            return Err(e);
        }
    };
    // renaming over an empty directory works on POSIX only: remove it first
    let placed = (if replaces_empty {
        std::fs::remove_dir(out)
    } else {
        Ok(())
    })
    .and_then(|()| std::fs::rename(&staging, out));
    if let Err(e) = placed {
        let _ = std::fs::remove_dir_all(&staging);
        return Err(io(out, e));
    }
    Ok(PrintSummary {
        out: out.display().to_string(),
        format: "md",
        docs: p.docs.iter().filter(|d| d.kind == PageKind::Doc).count(),
        folders: p.docs.iter().filter(|d| d.kind == PageKind::Folder).count(),
        assets: p.blobs.len(),
        pages: None,
        bytes,
        warnings: p.warnings.clone(),
    })
}

/// Writes the files of the tree under `root`; the bytes written. The TechDocs layout writes the
/// generated header; the others write what they always wrote.
fn write_tree(p: &Print, root: &Path, layout: Layout) -> Result<u64, RdyError> {
    emit_files(p, layout, layout == Layout::Techdocs, |path, data| {
        put(&root.join(path), data)
    })
}

/// Hands each file of the tree to `emit` as its path (`/` separators, relative to the tree's
/// root) and bytes, in a fixed order, and returns the bytes handed over. `generated` puts the
/// header in every Markdown and YAML file; assets are never changed. The durable writer and a
/// process that collects the bytes use the same function, so both get the same files.
pub fn emit_files(
    p: &Print,
    layout: Layout,
    generated: bool,
    mut emit: impl FnMut(&str, &[u8]) -> Result<(), RdyError>,
) -> Result<u64, RdyError> {
    let base = match layout {
        Layout::Plain => "",
        Layout::Mkdocs | Layout::Techdocs => "docs/",
    };
    let mut bytes = 0u64;
    let mut write = |path: String, data: &[u8]| -> Result<(), RdyError> {
        bytes += data.len() as u64;
        emit(&path, data)
    };
    write(
        format!("{base}index.md"),
        title_file(p, generated).as_bytes(),
    )?;
    for d in &p.docs {
        write(
            format!("{base}{}", md_path(&d.page)),
            page_file(p, d, generated).as_bytes(),
        )?;
    }
    for blob in p.blobs.values() {
        write(format!("{base}{}", blob.file), &blob.bytes)?;
    }
    if layout != Layout::Plain {
        write(
            "mkdocs.yml".to_string(),
            mkdocs_yml(p, layout, generated).as_bytes(),
        )?;
    }
    Ok(bytes)
}
