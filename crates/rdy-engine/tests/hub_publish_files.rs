/// Two paths with the same bytes are one files/known entry, sent once with the first path's
/// media type; the manifest keeps both paths and both media types.
#[test]
fn hpb12_files_known_deduplicates_hashes_and_keeps_paths() {
    let same = b"shared bytes";
    let src = source(vec![
        f("b/copy.txt", "text/plain", same),
        f("a/style.css", "text/css", same),
        page("index.html", 3),
        f("z.js", "text/javascript", b"other"),
    ]);
    let before = src.manifest().clone();
    let wire = fake();
    let (sent, asked) = upload(&src, limits(), &wire);
    let sent = sent.unwrap();

    // One request: three distinct hashes, by raw hash bytes, each with its size.
    let known = wire.known();
    assert_eq!(known.len(), 1);
    let mut want: Vec<FileIdentity> = before
        .files
        .iter()
        .map(|e| FileIdentity {
            hash: e.hash,
            size: e.size,
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    want.sort_by_key(|f| f.hash.0);
    assert_eq!(want.len(), 3);
    assert_eq!(known[0], want);

    // The shared bytes are sent once, under a/style.css's media type.
    let puts = wire.puts();
    assert_eq!(puts.len(), 3);
    let shared = puts
        .iter()
        .filter(|p| p.file.hash == Hash::of(same))
        .count();
    assert_eq!(shared, 1);
    let p = puts.iter().find(|p| p.file.hash == Hash::of(same)).unwrap();
    assert_eq!(p.media, "text/css");
    assert_eq!(p.body.as_deref(), Some(&same[..]));
    let total: u64 = want.iter().map(|f| f.size).sum();
    assert_eq!(
        sent,
        FilesSent {
            files: 3,
            bytes: total
        }
    );
    assert_eq!(asked, 1 + 3, "one context per request");

    // The manifest is unchanged, and the publish request carries both paths.
    assert_eq!(src.manifest(), &before);
    let m = src.manifest().clone();
    let c = publish_record(&record(None, &m), &m, PUSH, SITE, None, &wire, cx()).unwrap();
    assert_eq!(c, candidate());
    let body = &wire.published()[0].body;
    let files = body["manifest"]["files"].as_array().unwrap();
    let rows: Vec<(&str, &str)> = files
        .iter()
        .map(|f| {
            (
                f["path"].as_str().unwrap(),
                f["media_type"].as_str().unwrap(),
            )
        })
        .collect();
    assert_eq!(
        rows,
        [
            ("a/style.css", "text/css"),
            ("b/copy.txt", "text/plain"),
            ("index.html", "text/html"),
            ("z.js", "text/javascript"),
        ]
    );
    assert_eq!(files[0]["hash"], files[1]["hash"]);

    // One hash that claims two sizes is refused before any request.
    let mut bad = src.manifest().clone();
    let shared_hash = Hash::of(same);
    let i = bad
        .files
        .iter()
        .position(|e| e.path == "b/copy.txt")
        .unwrap();
    bad.files[i].size += 1;
    assert_eq!(bad.files[i].hash, shared_hash);
    let src = with_manifest(
        vec![
            f("b/copy.txt", "text/plain", same),
            f("a/style.css", "text/css", same),
            page("index.html", 3),
            f("z.js", "text/javascript", b"other"),
        ],
        bad,
    );
    let wire = fake();
    mismatch(upload(&src, limits(), &wire).0);
    assert_eq!(wire.requests(), 0);
}

/// Only the files the hub lacks are sent, in raw hash order, each with its own media type and
/// claim; an invalid missing list sends no file.
#[test]
fn hpb12_only_missing_files_are_sent_in_hash_order() {
    let files = || {
        vec![
            page("index.html", 100),
            f("a.txt", "text/plain", b"alpha"),
            f("b.txt", "text/plain", b"bravo"),
            f("img/c.png", "image/png", b"charlie png"),
            f("d.json", "application/json", b"{\"d\":1}"),
        ]
    };
    let src = source(files());
    let by_hash: BTreeMap<[u8; 32], &ManifestEntry> =
        src.manifest().files.iter().map(|e| (e.hash.0, e)).collect();
    let order: Vec<&ManifestEntry> = by_hash.values().copied().collect();
    let lacking: Vec<Hash> = [1, 3, 4].iter().map(|&i| order[i].hash).collect();

    let mut wire = fake();
    let answer = lacking.clone();
    wire.on_known = Box::new(move |_| Ok(answer.clone()));
    let (sent, asked) = upload(&src, limits(), &wire);
    let sent = sent.unwrap();
    let puts = wire.puts();
    assert_eq!(puts.len(), 3);
    for (p, want) in puts.iter().zip([order[1], order[3], order[4]]) {
        assert_eq!(
            p.file,
            FileIdentity {
                hash: want.hash,
                size: want.size
            }
        );
        assert_eq!(p.media, want.media_type);
        assert_eq!(p.len, want.size);
        let bytes = match &src.files[&want.path] {
            Body::Bytes(b) => b.clone(),
            Body::Generated(_) => unreachable!(),
        };
        assert_eq!(p.body.as_deref(), Some(&bytes[..]));
    }
    let bytes = order[1].size + order[3].size + order[4].size;
    assert_eq!(sent, FilesSent { files: 3, bytes });
    assert_eq!(asked, 4);

    // The hub holds everything: one files/known request and nothing else.
    let mut wire = fake();
    wire.on_known = Box::new(|_| Ok(vec![]));
    let (sent, asked) = upload(&source(files()), limits(), &wire);
    assert_eq!(sent.unwrap(), FilesSent { files: 0, bytes: 0 });
    assert_eq!((wire.known().len(), wire.puts().len(), asked), (1, 0, 1));

    // A missing list out of order, repeated, or naming a hash not asked for is a protocol
    // error, and no file is sent.
    let unknown = Hash::of(b"never asked");
    let bad: [Vec<Hash>; 3] = [
        vec![lacking[1], lacking[0]],
        vec![lacking[0], lacking[0]],
        vec![lacking[0], unknown],
    ];
    for list in bad {
        let mut wire = fake();
        wire.on_known = Box::new(move |_| Ok(list.clone()));
        let e = err(upload(&source(files()), limits(), &wire).0);
        same(&e, &upstream_protocol());
        assert_eq!(e.code, E_UPSTREAM_PROTOCOL);
        assert_eq!((wire.known().len(), wire.puts().len()), (1, 0));
    }
}

/// Bytes that differ from the manifest in any way, a notice offset that does not point at the
/// exact empty slot, and a missing, extra or unsorted path are refused before any request;
/// bytes that change after the check are refused before their file request completes.
#[test]
fn hpb12_changed_bytes_and_bad_slots_refuse_before_publish() {
    // A good site validates to its manifest hash; a slot across a buffer boundary is found.
    let src = source(vec![
        page("index.html", BUFFER - 7),
        f("a.txt", "text/plain", b"a"),
    ]);
    let want = manifest_hash(src.manifest(), MANIFEST_RECIPE).unwrap();
    assert_eq!(validate_artifact(&src, limits()).unwrap(), want);
    assert!(src.stats.largest_read.load(Ordering::Relaxed) <= BUFFER);

    let refuse = |src: Mem| {
        let wire = fake();
        mismatch(validate_artifact(&src, limits()));
        mismatch(upload(&src, limits(), &wire).0);
        assert_eq!(
            wire.requests(),
            0,
            "no request before the artifact is checked"
        );
    };

    // The slot's bytes are not exactly the empty slot (also across a buffer boundary).
    for before in [10, BUFFER - 7] {
        let mut p = page("index.html", before);
        if let Body::Bytes(b) = &mut p.body {
            b[before + NOTICE_SLOT.len() - 1] = b'!';
        }
        refuse(source(vec![p]));
    }
    // The offset is one byte early or late, though the bytes and hash are right.
    for shift in [-1i64, 1] {
        let p = page("index.html", 10);
        let mut m = Manifest {
            files: vec![entry(&p)],
        };
        m.files[0].notice_offset = Some((10 + shift) as u64);
        refuse(with_manifest(vec![p], m));
    }
    // A file shorter, longer, or of the same length with one changed byte.
    let base = || page("index.html", 20);
    let stated = Manifest {
        files: vec![entry(&base())],
    };
    let edit = |change: fn(&mut Vec<u8>)| {
        let mut p = base();
        if let Body::Bytes(b) = &mut p.body {
            change(b);
        }
        with_manifest(vec![p], stated.clone())
    };
    refuse(edit(|b| {
        b.pop();
    }));
    refuse(edit(|b| b.push(b'x')));
    refuse(edit(|b| b[0] = b'b'));
    // A path the source lacks, a path the manifest lacks, and paths out of order.
    let two = || vec![base(), f("a.txt", "text/plain", b"a")];
    let mut m = Manifest {
        files: two().iter().map(entry).collect(),
    };
    m.files.push(entry(&f("c.txt", "text/plain", b"c")));
    refuse(with_manifest(two(), m));
    let m = Manifest {
        files: vec![entry(&base())],
    };
    refuse(with_manifest(two(), m));
    let mut src = source(two());
    src.unsorted = true;
    refuse(src);

    // Bytes that change after the check, at the same length or with more bytes: the file's
    // request never receives its last bytes, and the upload is refused.
    for later in [b"b".to_vec(), b"ab".to_vec()] {
        let mut src = source(vec![f("a.txt", "text/plain", b"a")]);
        src.later.insert("a.txt".into(), Body::Bytes(later));
        let wire = fake();
        mismatch(upload(&src, limits(), &wire).0);
        let puts = wire.puts();
        assert_eq!(puts.len(), 1);
        assert_eq!(puts[0].len, 0, "the changed bytes were withheld");
        assert!(wire.published().is_empty());
    }
}

/// The supported maximum: 32,000 files and 192 MiB, one of them a generated file never held
/// whole, pass the check and the upload; one byte or one file over the negotiated limit is
/// refused before any file is opened.
#[test]
fn hpb12_full_supported_manifest_and_artifact_fit() {
    let mut files: Vec<F> = (1..HUB_FILES)
        .map(|i| F {
            path: format!("f/{i:05}.txt"),
            media: "text/plain",
            body: Body::Bytes(format!("file {i}\n").into_bytes()),
            notice: None,
        })
        .collect();
    let small: u64 = files.iter().map(|f| f.body.len()).sum();
    files.push(F {
        path: "big.bin".into(),
        media: "application/octet-stream",
        body: Body::Generated(HUB_BYTES - small),
        notice: None,
    });
    let src = source(files);
    assert_eq!(src.manifest().files.len(), HUB_FILES as usize);
    let total: u64 = src.manifest().files.iter().map(|e| e.size).sum();
    assert_eq!(total, HUB_BYTES);

    // One byte or one file over the negotiated limit, before any open or request.
    for (lim, text) in [
        (
            ArtifactLimits {
                bytes: HUB_BYTES - 1,
                files: HUB_FILES,
            },
            format!("{} bytes", HUB_BYTES - 1),
        ),
        (
            ArtifactLimits {
                bytes: HUB_BYTES,
                files: HUB_FILES - 1,
            },
            format!("{} files", HUB_FILES - 1),
        ),
    ] {
        let wire = fake();
        for e in [
            err(validate_artifact(&src, lim)),
            err(upload(&src, lim, &wire).0),
        ] {
            assert_eq!(
                (e.code, e.message.as_str(), e.fix.as_str()),
                (
                    E_LIMIT,
                    format!("publication artifact exceeds the hub limit of {text}").as_str(),
                    "publish a smaller site"
                )
            );
        }
        assert_eq!(src.stats.opens.load(Ordering::Relaxed), 0);
        assert_eq!(wire.requests(), 0);
    }

    // A limit above core's caps is held to them, and the maximum fits.
    let generous = ArtifactLimits {
        bytes: u64::MAX,
        files: u32::MAX,
    };
    let want = manifest_hash(src.manifest(), MANIFEST_RECIPE).unwrap();
    assert_eq!(validate_artifact(&src, generous).unwrap(), want);

    // The upload at the hub's exact default limits: one files/known request of 32,000 hashes,
    // then every file, read in buffers of at most 65,536 bytes.
    let wire = fake();
    let (sent, asked) = upload(&src, limits(), &wire);
    assert_eq!(
        sent.unwrap(),
        FilesSent {
            files: HUB_FILES,
            bytes: HUB_BYTES
        }
    );
    assert_eq!(asked, 1 + HUB_FILES as usize);
    let known = wire.known();
    assert_eq!((known.len(), known[0].len()), (1, HUB_FILES as usize));
    let puts = wire.puts();
    assert_eq!(puts.len(), HUB_FILES as usize);
    assert_eq!(puts.iter().map(|p| p.len).sum::<u64>(), HUB_BYTES);
    let big = puts.iter().find(|p| p.len == HUB_BYTES - small).unwrap();
    assert_eq!(big.media, "application/octet-stream");
    assert!(src.stats.largest_read.load(Ordering::Relaxed) <= BUFFER);
    // Each byte was read three times: by the check above, then by the upload's own check and
    // by its file requests. Nothing else read the source.
    assert_eq!(src.stats.bytes.load(Ordering::Relaxed), 3 * HUB_BYTES);
}

/// The publish request pins the record's inputs: repo id, tag, landing, the profile as null
/// for implicit:org or as exactly {id, version}, the sorted selection, the manifest recipe and
/// hash and the render inputs, with no audience or selection identity. `keep_latest` reaches
/// the wire unchanged and sits beside the record only when given.
#[test]
fn hpb12_record_has_pinned_selection_inputs_and_null_implicit_identity() {
    let src = small_site();
    let m = src.manifest().clone();
    let wire = fake();
    let c = publish_record(&record(None, &m), &m, PUSH, SITE, None, &wire, cx()).unwrap();
    assert_eq!(c, candidate());
    let published = wire.published();
    assert_eq!(published.len(), 1);
    let body = &published[0].body;
    let want = json!({
        "repo_id": "abababababababababababababababab",
        "tag": "v1.2.0",
        "landing": h(3).to_string(),
        "profile": null,
        "selection": [
            {"id": "D-0A000", "version": h(4).to_string(), "redaction": null},
            {"id": "D-0B000", "version": h(5).to_string(), "redaction": h(6).to_string()},
        ],
        "selection_hash": h(7).to_string(),
        "manifest_recipe": 1,
        "manifest_hash": manifest_hash(&m, 1).unwrap().to_string(),
        "render_inputs": serde_json::to_value(inputs()).unwrap(),
    });
    assert_eq!(body["record"], want);
    // Neither the record nor the request names an audience or a selection identity (the pack
    // inside the render inputs names the profile type's own `audience` field, which is data).
    for object in [&body["record"], body] {
        for key in ["audience", "selection_identity"] {
            assert!(object.get(key).is_none(), "{key} in {object}");
        }
    }

    // An explicit profile is exactly {id, version}: the revision the tag pins.
    let wire = fake();
    let explicit = ProfileIdentity {
        id: block("PUB-0A1B2"),
        version: h(8),
    };
    publish_record(
        &record(Some(explicit), &m),
        &m,
        PUSH,
        SITE,
        None,
        &wire,
        cx(),
    )
    .unwrap();
    assert_eq!(
        wire.published()[0].body["record"]["profile"],
        json!({"id": "PUB-0A1B2", "version": h(8).to_string()})
    );

    // keep_latest reaches the wire unchanged, beside the record and only when given.
    for keep in [Some(true), Some(false), None] {
        let wire = fake();
        publish_record(&record(None, &m), &m, PUSH, SITE, keep, &wire, cx()).unwrap();
        let p = &wire.published()[0];
        assert_eq!(p.keep_latest, keep);
        let top: BTreeSet<&str> = p
            .body
            .as_object()
            .unwrap()
            .keys()
            .map(String::as_str)
            .collect();
        let mut want: BTreeSet<&str> = ["push", "site", "record", "manifest"].into();
        if keep.is_some() {
            want.insert("keep_latest");
        }
        assert_eq!(top, want);
        assert_eq!(p.body.get("keep_latest"), keep.map(Value::Bool).as_ref());
        assert!(p.body["record"].get("keep_latest").is_none());
    }

    // The record is checked before the request: recipe 1 recomputed, the selection sorted.
    let wire = fake();
    let mut r = record(None, &m);
    r.manifest_hash = h(9);
    mismatch(publish_record(&r, &m, PUSH, SITE, None, &wire, cx()));
    let mut r = record(None, &m);
    r.selection.reverse();
    let e = err(publish_record(&r, &m, PUSH, SITE, None, &wire, cx()));
    assert_eq!(e.code, E_BAD_INPUT);
    let mut r = record(None, &m);
    r.selection.push(r.selection[1].clone());
    assert_eq!(
        err(publish_record(&r, &m, PUSH, SITE, None, &wire, cx())).code,
        E_BAD_INPUT
    );
    let mut r = record(None, &m);
    r.manifest_recipe = 2;
    let e = err(publish_record(&r, &m, PUSH, SITE, None, &wire, cx()));
    assert_eq!(
        (e.code, e.message.as_str()),
        (E_BAD_INPUT, "manifest recipe 2 is not supported")
    );
    assert_eq!(wire.requests(), 0);
}

/// A failed files/known, file or publish request is never sent again, and a lost write stays
/// uncertain.
#[test]
fn hpb12_file_or_publish_failure_never_retries() {
    // files/known fails: no file is sent.
    let mut wire = fake();
    wire.on_known = Box::new(|_| Err(upstream_transport()));
    let e = err(upload(&small_site(), limits(), &wire).0);
    same(&e, &upstream_transport());
    assert_eq!(e.code, E_UPSTREAM_TRANSPORT);
    assert_eq!((wire.known().len(), wire.puts().len()), (1, 0));

    // The second file's reply is lost: uncertain, and no file is sent again or after it.
    let mut wire = fake();
    wire.on_put = Box::new(|i, file| {
        if i == 1 {
            Err(upstream_uncertain())
        } else {
            Ok(*file)
        }
    });
    let e = err(upload(&small_site(), limits(), &wire).0);
    same(&e, &upstream_uncertain());
    assert_eq!(e.code, E_UPSTREAM_UNCERTAIN);
    let puts = wire.puts();
    assert_eq!(puts.len(), 2);
    assert_ne!(puts[0].file, puts[1].file);

    // A reply that names another file or size is uncertain too.
    let mut wire = fake();
    wire.on_put = Box::new(|_, file| {
        Ok(FileIdentity {
            hash: file.hash,
            size: file.size + 1,
        })
    });
    let e = err(upload(&small_site(), limits(), &wire).0);
    same(&e, &upstream_uncertain());
    assert_eq!(wire.puts().len(), 1);

    // A refusal passes through unchanged.
    let mut wire = fake();
    wire.on_put = Box::new(|_, _| Err(upstream_refused()));
    let e = err(upload(&small_site(), limits(), &wire).0);
    same(&e, &upstream_refused());
    assert_eq!(e.code, E_UPSTREAM_REFUSED);
    assert_eq!(wire.puts().len(), 1);

    // A context that cannot be had sends nothing further.
    let wire = fake();
    let src = small_site();
    let mut asked = 0;
    let mut context = || {
        asked += 1;
        if asked == 2 {
            Err(upstream_transport())
        } else {
            Ok(cx())
        }
    };
    let e = err(upload_files(&src, PUSH, limits(), &wire, &mut context));
    same(&e, &upstream_transport());
    assert_eq!((wire.known().len(), wire.puts().len(), asked), (1, 0, 2));

    // The publish reply is lost: uncertain, sent once. A refusal is sent once too.
    let m = small_site().manifest().clone();
    for (reply, code) in [
        (upstream_uncertain(), E_UPSTREAM_UNCERTAIN),
        (upstream_refused(), E_UPSTREAM_REFUSED),
    ] {
        let mut wire = fake();
        let r2 = reply.clone();
        wire.on_publish = Box::new(move || Err(r2.clone()));
        let e = err(publish_record(
            &record(None, &m),
            &m,
            PUSH,
            SITE,
            None,
            &wire,
            cx(),
        ));
        same(&e, &reply);
        assert_eq!(e.code, code);
        assert_eq!(wire.published().len(), 1);
        assert_eq!(wire.requests(), 1);
    }
}
