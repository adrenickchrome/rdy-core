/// A file's bytes: literal, or `len` generated bytes that are never held whole.
#[derive(Clone)]
enum Body {
    Bytes(Vec<u8>),
    Generated(u64),
}

impl Body {
    fn len(&self) -> u64 {
        match self {
            Body::Bytes(b) => b.len() as u64,
            Body::Generated(n) => *n,
        }
    }
}

/// The repeating cycle of generated bytes: 251 is prime, so no buffer boundary aligns with it.
fn cycle() -> &'static [u8] {
    static CYCLE: OnceLock<Vec<u8>> = OnceLock::new();
    CYCLE.get_or_init(|| (0..BUFFER + 251).map(|i| (i % 251) as u8).collect())
}

#[derive(Default)]
struct Stats {
    opens: AtomicUsize,
    bytes: AtomicU64,
    largest_read: AtomicUsize,
}

/// A reader over one body that counts what it yields.
struct Counting<'a> {
    body: Body,
    pos: u64,
    stats: &'a Stats,
}

impl Read for Counting<'_> {
    fn read(&mut self, out: &mut [u8]) -> io::Result<usize> {
        self.stats
            .largest_read
            .fetch_max(out.len(), Ordering::Relaxed);
        let left = self.body.len() - self.pos;
        let n = (out.len() as u64).min(left) as usize;
        match &self.body {
            Body::Bytes(b) => {
                let at = self.pos as usize;
                out[..n].copy_from_slice(&b[at..at + n]);
            }
            Body::Generated(_) => {
                let mut done = 0;
                while done < n {
                    let phase = ((self.pos + done as u64) % 251) as usize;
                    let take = (n - done).min(BUFFER);
                    out[done..done + take].copy_from_slice(&cycle()[phase..phase + take]);
                    done += take;
                }
            }
        }
        self.pos += n as u64;
        self.stats.bytes.fetch_add(n as u64, Ordering::Relaxed);
        Ok(n)
    }
}

/// An immutable in-memory artifact. `later` gives the bytes a path yields from its second open
/// on, to model a source that changed after it was checked.
struct Mem {
    manifest: Manifest,
    files: BTreeMap<String, Body>,
    later: BTreeMap<String, Body>,
    opened: Mutex<BTreeMap<String, usize>>,
    unsorted: bool,
    stats: Stats,
}

impl ArtifactSource for Mem {
    fn manifest(&self) -> &Manifest {
        &self.manifest
    }

    fn paths(&self) -> Vec<&str> {
        let mut paths: Vec<&str> = self.files.keys().map(String::as_str).collect();
        if self.unsorted {
            paths.reverse();
        }
        paths
    }

    fn open(&self, path: &str) -> Result<Box<dyn Read + '_>, RdyError> {
        self.stats.opens.fetch_add(1, Ordering::Relaxed);
        let n = {
            let mut opened = self.opened.lock().unwrap();
            let n = opened.entry(path.to_string()).or_default();
            *n += 1;
            *n
        };
        let body = match (n, self.later.get(path)) {
            (2.., Some(b)) => b.clone(),
            _ => self
                .files
                .get(path)
                .expect("only listed paths are opened")
                .clone(),
        };
        Ok(Box::new(Counting {
            body,
            pos: 0,
            stats: &self.stats,
        }))
    }
}

/// One file: its path, media type, bytes and notice offset.
struct F {
    path: String,
    media: &'static str,
    body: Body,
    notice: Option<u64>,
}

fn f(path: &str, media: &'static str, bytes: &[u8]) -> F {
    F {
        path: path.into(),
        media,
        body: Body::Bytes(bytes.to_vec()),
        notice: None,
    }
}

/// An HTML page with an empty notice slot after `before` bytes.
fn page(path: &str, before: usize) -> F {
    let mut bytes = vec![b'a'; before];
    bytes.extend_from_slice(NOTICE_SLOT);
    bytes.extend_from_slice(b"</body>");
    F {
        path: path.into(),
        media: "text/html",
        body: Body::Bytes(bytes),
        notice: Some(before as u64),
    }
}

fn hash_of(body: &Body) -> Hash {
    match body {
        Body::Bytes(b) => Hash::of(b),
        Body::Generated(n) => {
            let stats = Stats::default();
            let mut r = Counting {
                body: body.clone(),
                pos: 0,
                stats: &stats,
            };
            hash_reader(&mut r, *n).unwrap()
        }
    }
}

fn entry(file: &F) -> ManifestEntry {
    ManifestEntry {
        path: file.path.clone(),
        hash: hash_of(&file.body),
        media_type: file.media.into(),
        size: file.body.len(),
        notice_offset: file.notice,
    }
}

/// A source whose manifest states exactly its files.
fn source(files: Vec<F>) -> Mem {
    let manifest = Manifest {
        files: files.iter().map(entry).collect(),
    };
    with_manifest(files, manifest)
}

/// A source with its own `manifest`, which may disagree with the files.
fn with_manifest(files: Vec<F>, manifest: Manifest) -> Mem {
    Mem {
        manifest,
        files: files.into_iter().map(|f| (f.path, f.body)).collect(),
        later: BTreeMap::new(),
        opened: Mutex::new(BTreeMap::new()),
        unsorted: false,
        stats: Stats::default(),
    }
}

fn limits() -> ArtifactLimits {
    ArtifactLimits {
        bytes: HUB_BYTES,
        files: HUB_FILES,
    }
}

