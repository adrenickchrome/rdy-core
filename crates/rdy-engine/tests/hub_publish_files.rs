/// One file request the hub read: its claim, media type, body length and body.
#[derive(Clone, Debug, PartialEq)]
struct Put {
    file: FileIdentity,
    media: String,
    len: u64,
    /// The body, when it is at most 1 MiB; a larger one is only counted.
    body: Option<Vec<u8>>,
}

/// One publish request: its encoded body and the `keep_latest` the call carried.
#[derive(Clone, Debug)]
struct Published {
    body: Value,
    keep_latest: Option<bool>,
}

type KnownFn = Box<dyn Fn(&[FileIdentity]) -> Result<Vec<Hash>, RdyError> + Send + Sync>;
type PutFn = Box<dyn Fn(usize, &FileIdentity) -> Result<FileIdentity, RdyError> + Send + Sync>;
type PublishFn = Box<dyn Fn() -> Result<Candidate, RdyError> + Send + Sync>;

/// A wire that answers from closures and records every request. A body that cannot be read
/// to its end is a lost write: `E_UPSTREAM_UNCERTAIN`.
struct Fake {
    on_known: KnownFn,
    on_put: PutFn,
    on_publish: PublishFn,
    known: Mutex<Vec<Vec<FileIdentity>>>,
    puts: Mutex<Vec<Put>>,
    published: Mutex<Vec<Published>>,
}

/// A wire that lacks every file and accepts every request.
fn fake() -> Fake {
    Fake {
        on_known: Box::new(|files| Ok(files.iter().map(|f| f.hash).collect())),
        on_put: Box::new(|_, file| Ok(*file)),
        on_publish: Box::new(|| Ok(candidate())),
        known: Mutex::new(vec![]),
        puts: Mutex::new(vec![]),
        published: Mutex::new(vec![]),
    }
}

impl Fake {
    fn known(&self) -> Vec<Vec<FileIdentity>> {
        self.known.lock().unwrap().clone()
    }
    fn puts(&self) -> Vec<Put> {
        self.puts.lock().unwrap().clone()
    }
    fn published(&self) -> Vec<Published> {
        self.published.lock().unwrap().clone()
    }
    fn requests(&self) -> usize {
        self.known().len() + self.puts().len() + self.published().len()
    }
}

impl PublishWire for Fake {
    fn discovery(&self, _: &UploadContext, _: &str) -> Result<Discovery, RdyError> {
        panic!("the file sender never discovers")
    }
    fn state(&self, _: &UploadContext, _: &StateRequest) -> Result<PublishState, RdyError> {
        panic!("the file sender never reads state")
    }
    fn known(
        &self,
        _: &UploadContext,
        _: &str,
        _: &[ObjectKey],
    ) -> Result<Vec<ObjectKey>, RdyError> {
        panic!("the file sender never sends objects")
    }
    fn put_objects(
        &self,
        _: &UploadContext,
        _: &str,
        _: &mut dyn Read,
        _: u64,
    ) -> Result<ObjectPut, RdyError> {
        panic!("the file sender never sends objects")
    }

    fn known_files(
        &self,
        _: &UploadContext,
        push: &str,
        files: &[FileIdentity],
    ) -> Result<Vec<Hash>, RdyError> {
        assert_eq!(push, PUSH);
        self.known.lock().unwrap().push(files.to_vec());
        (self.on_known)(files)
    }

    fn put_file(
        &self,
        _: &UploadContext,
        push: &str,
        file: &FileIdentity,
        media_type: &str,
        body: &mut dyn Read,
    ) -> Result<FileIdentity, RdyError> {
        assert_eq!(push, PUSH);
        let index = self.puts.lock().unwrap().len();
        let keep = file.size <= 1 << 20;
        let mut held = Vec::new();
        let mut len = 0u64;
        let mut buf = vec![0u8; BUFFER];
        let mut lost = false;
        loop {
            match body.read(&mut buf) {
                Ok(0) => break,
                Ok(n) => {
                    len += n as u64;
                    if keep {
                        held.extend_from_slice(&buf[..n]);
                    }
                }
                Err(e) if e.kind() == io::ErrorKind::Interrupted => continue,
                Err(_) => {
                    lost = true;
                    break;
                }
            }
        }
        self.puts.lock().unwrap().push(Put {
            file: *file,
            media: media_type.into(),
            len,
            body: keep.then_some(held),
        });
        if lost {
            return Err(upstream_uncertain());
        }
        (self.on_put)(index, file)
    }

    fn publish(
        &self,
        cx: &UploadContext,
        push: &str,
        site: &str,
        record: &PublicationInputs,
        manifest: &Manifest,
        keep_latest: Option<bool>,
    ) -> Result<Candidate, RdyError> {
        assert_eq!(cx.bearer.expose(), ACCESS);
        // The real wire's encoder, so the pinned JSON is what the hub would read.
        let bytes = encode_publish(push, site, record, manifest, keep_latest).unwrap();
        self.published.lock().unwrap().push(Published {
            body: serde_json::from_slice(&bytes).unwrap(),
            keep_latest,
        });
        (self.on_publish)()
    }
}

