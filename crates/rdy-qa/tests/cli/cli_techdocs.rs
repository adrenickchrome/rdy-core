//! hpb4 (D-5X0ZK, D-KQ4CA, D-8QV9G): `rdy export --format md --layout techdocs` and `rdy_export`
//! with `layout: "techdocs"` write the same tree, with and without a profile, and refuse a
//! layout with another format or a layout that is not in the list.
use rdy_engine::Rdy;
use rdy_mcp::params::parse_params;
use rdy_mcp::tools::ExportParams;
use rdy_qa::daemon::{Served, short_tempdir};
use rdy_qa::fixtures::{approver, land, write};
use rdy_qa::mcp::{McpClient, Reply};
use serde_json::{Value, json};
use std::collections::BTreeMap;
use std::path::Path;

/// A served project: the folder `area` with the doc `chosen`, a doc `outdoc` outside it and the
/// profile `orgp` on `area`; landed and tagged.
fn seeded() -> Served {
    let s = Served::new();
    let mut r = Rdy::open(s.dir.path()).unwrap();
    let w = write(
        &mut r,
        "work",
        json!([
            {"op": "create", "type": "folder", "id": "$area", "fields": {"name": "area", "title": "Area"}},
            {"op": "create", "type": "doc", "id": "$chosen", "parent": "$area", "fields": {"name": "chosen", "title": "Chosen page", "doc_type": "page"}},
            {"op": "create", "type": "prose", "parent": "$chosen", "body": "Chosen prose words."},
            {"op": "create", "type": "doc", "id": "$out", "fields": {"name": "outdoc", "title": "OUTCANARY doc", "doc_type": "page"}},
            {"op": "create", "type": "prose", "parent": "$out", "body": "OUTCANARY words."},
            {"op": "create", "type": "doc", "id": "$admin", "fields": {"name": "admin", "title": "Admin page", "doc_type": "page"}}
        ]),
    )
    .unwrap();
    let id = |k: &str| w.created[k].clone();
    write(
        &mut r,
        "work",
        json!([
            {"op": "create", "type": "publication_profile", "parent": id("$admin"),
             "fields": {"key": "orgp", "title": "Title of orgp", "audience": "org", "select": [id("$area")]}}
        ]),
    )
    .unwrap();
    land(&mut r, "work").unwrap();
    r.tag(&approver(), "v1.0.0", None, None).unwrap();
    r.close().unwrap();
    s
}

fn agent(s: &Served) -> McpClient {
    let mut c = McpClient::start_proxy(s);
    c.call(
        "rdy_session",
        json!({"actor": "agent:a", "run": "a", "role": "writer"}),
    )
    .ok();
    c
}

fn refused(r: Reply) -> (String, String, String) {
    let Reply::ToolError(e) = r else {
        panic!("expected a tool error, got {r:?}")
    };
    let s = |k: &str| e[k].as_str().unwrap_or_default().to_string();
    (s("code"), s("message"), s("fix"))
}

/// Every file under `p`, by its path relative to `p`.
fn files_of(p: &Path) -> BTreeMap<String, Vec<u8>> {
    let mut out = BTreeMap::new();
    let mut stack = vec![p.to_path_buf()];
    while let Some(d) = stack.pop() {
        for e in std::fs::read_dir(&d).unwrap() {
            let f = e.unwrap().path();
            if f.is_dir() {
                stack.push(f);
            } else {
                let rel = f
                    .strip_prefix(p)
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/");
                out.insert(rel, std::fs::read(&f).unwrap());
            }
        }
    }
    out
}

fn without_out(mut v: Value) -> Value {
    v.as_object_mut().unwrap().remove("out");
    v
}

#[test]
fn hpb4_cli_and_mcp_export_the_same_techdocs_tree() {
    let s = seeded();
    let scratch = short_tempdir();
    let mut c = agent(&s);
    for (name, profile) in [("source", None), ("profile", Some("orgp"))] {
        let cli = scratch.path().join(format!("cli-{name}"));
        let mut args = vec![
            "--json",
            "export",
            "--out",
            cli.to_str().unwrap(),
            "--format",
            "md",
            "--layout",
            "techdocs",
        ];
        if let Some(p) = profile {
            args.extend(["--profile", p]);
        }
        let (ok, cv) = s.json(&args);
        assert!(ok, "{name}: {cv}");
        let tool = scratch.path().join(format!("mcp-{name}"));
        let mut p = json!({"out": tool.to_str().unwrap(), "format": "md", "layout": "techdocs"});
        if let Some(pr) = profile {
            p["profile"] = json!(pr);
        }
        let tv = c.call("rdy_export", p).ok();
        assert_eq!(
            without_out(cv.clone()),
            without_out(tv),
            "{name}: the same reply"
        );
        let (a, b) = (files_of(&cli), files_of(&tool));
        assert!(a == b, "{name}: the CLI and the tool write the same bytes");
        let yml = String::from_utf8(a["mkdocs.yml"].clone()).unwrap();
        assert!(
            yml.starts_with("# generated by rdy, edit in rdy\nsite_name: "),
            "{yml}"
        );
        assert!(
            yml.contains("\ndocs_dir: docs\nplugins:\n  - techdocs-core\nnav:\n"),
            "{yml}"
        );
        assert!(
            a.keys()
                .all(|k| k == "mkdocs.yml" || k.starts_with("docs/"))
        );
        let index = String::from_utf8(a["docs/index.md"].clone()).unwrap();
        assert!(
            index.contains("\n---\n\n<!-- generated by rdy, edit in rdy -->\n\n# "),
            "{index}"
        );
        let all: String = a
            .values()
            .map(|b| String::from_utf8_lossy(b).into_owned())
            .collect();
        match profile {
            Some(_) => assert!(!all.contains("OUTCANARY"), "{name}"),
            None => assert!(all.contains("OUTCANARY"), "{name}"),
        }
        assert_eq!(cv["format"], "md", "{name}");
    }
}

#[test]
fn hpb4_techdocs_wrong_format_and_unknown_layout_refuse() {
    let s = seeded();
    let dir = s.dir.path();
    let want = "--layout techdocs applies to the md format only";
    for (out, format) in [("z.pdf", "pdf"), ("z.html", "html")] {
        let o = s.rdy(&[
            "export", "--out", out, "--format", format, "--layout", "techdocs",
        ]);
        assert!(!o.status.success(), "{format}");
        let err = String::from_utf8_lossy(&o.stderr);
        assert!(err.contains(want), "{err}");
        assert!(
            err.contains("drop --layout, or export with --format md"),
            "{err}"
        );
        assert!(!dir.join(out).exists(), "{format}");
    }
    // a layout outside the list, in any case, is refused before anything is written
    for layout in ["hugo", "TechDocs", "tech-docs", ""] {
        let o = s.rdy(&["export", "--out", "u", "--format", "md", "--layout", layout]);
        assert!(!o.status.success(), "{layout:?}");
        assert!(!dir.join("u").exists(), "{layout:?}");
    }

    let mut c = agent(&s);
    for (out, format) in [("l.pdf", "pdf"), ("l.html", "html")] {
        for profile in [None, Some("orgp")] {
            let mut p = json!({"out": out, "format": format, "layout": "techdocs"});
            if let Some(pr) = profile {
                p["profile"] = json!(pr);
            }
            let (code, message, fix) = refused(c.call("rdy_export", p));
            assert_eq!(code, "E_BAD_INPUT", "{format}");
            assert_eq!(message, want);
            assert_eq!(fix, "drop --layout, or export with --format md");
            assert!(!dir.join(out).exists(), "{format}");
        }
    }
    for layout in ["hugo", "TechDocs", ""] {
        let (code, ..) = refused(c.call(
            "rdy_export",
            json!({"out": "u", "format": "md", "layout": layout}),
        ));
        assert_eq!(code, "E_BAD_INPUT", "{layout:?}");
        assert!(!dir.join("u").exists());
    }
    // strict parameters: the layout list, and an unknown key
    let parse =
        |args: Value| parse_params::<ExportParams>("rdy_export", args.as_object().unwrap().clone());
    assert!(parse(json!({"out": "x", "format": "md", "layout": "techdocs"})).is_ok());
    for args in [
        json!({"out": "x", "format": "md", "layout": "TechDocs"}),
        json!({"out": "x", "format": "md", "layout": "tech"}),
        json!({"out": "x", "format": "md", "layouts": "techdocs"}),
    ] {
        assert_eq!(
            parse(args.clone()).unwrap_err().code,
            "E_BAD_INPUT",
            "{args}"
        );
    }
    assert!(!dir.join("u").exists());
}
